    private void btncadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncadastrarActionPerformed
        
        try {
        String nome = txtnome.getText();
        String cpf = txtcpf.getText();
        String numero = txttelefone.getText();
        String geren = cbmgerente.getSelectedItem().toString();
        String usua = cbmusuario.getSelectedItem().toString();
        
    coringaJPA<usuario> a = new coringaJPA<>(usuario.class);
     coringaJPA<gerente> ge = new coringaJPA<>(gerente.class);
    
        usuario u = a.buscarPorLogin(usua);
        gerente gen = ge.buscarPorNome(geren);
        
          barbeiro bar = new barbeiro();
          bar.setNome(nome);
          bar.setCpf(cpf);
          bar.setTelefone(numero);
          bar.setUsuario(u);
          bar.setGerente(gen);
          
          b.salvar(bar);
          
          JOptionPane.showMessageDialog(null, nome +" Cadastrado com sucesso!");
          } catch (Exception e) {
        JOptionPane.showMessageDialog(this,"Erro ao cadastrar: " + e.getMessage());
        e.printStackTrace();
    }
        atualizarDados();
        
    }//GEN-LAST:event_btncadastrarActionPerformed

    private void btnexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexcluirActionPerformed
        try{
        int linha = tabela.getSelectedRow();
        
        if (linha == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "selecione um barbeiro para excluir!");
            return;
        } else {
            int id;
            id = (int) tabela.getValueAt(linha, 0);
            b.excluir(id);
            javax.swing.JOptionPane.showMessageDialog(this,
                    "barbeiro excluído com sucesso!");
        }
        
        }catch(Exception e){
        JOptionPane.showMessageDialog(null,"O Barbeiro nâo pode ser excluído" + e);
        }atualizarDados();
    }//GEN-LAST:event_btnexcluirActionPerformed

    private void carregarUsuarios() {
        
    coringaJPA<gerente> c = new coringaJPA<>(gerente.class);
    coringaJPA<usuario> a = new coringaJPA<>(usuario.class);
    
        cbmusuario.removeAllItems();
        cbmgerente.removeAllItems();
        
        List<usuario> usu = a.listar();
        List<gerente> gen = c.listar();
        
        for (usuario u : usu) {
            
            cbmusuario.addItem(u.getLogin());
        }
        
        for (gerente g : gen) {
            
            cbmgerente.addItem(g.getNome());
        }
        
    }
        
    private void iniciartabela() {

        if (table == null) {

            table = new DefaultTableModel(
                    new Object[]{
                        "ID", "Nome", "CPF","Telefone","Usuario","Gerente"}, 0) {

                @Override
                public boolean isCellEditable(int row, int column) {

                    return false; // ID não pode ser alterado
                }
            };
            tabela.setModel(table);
        }

        atualizarDados();
    }
    
    private void atualizarDados() {

        List<barbeiro> lista = b.listar();

        table.setRowCount(0);

        for (barbeiro b : lista) {
            table.addRow(new Object[]{
                b.getIdbarbeiro(),
                b.getNome(),
                b.getCpf(),
                b.getTelefone(),
                b.getUsuario().getLogin(),
                b.getGerente().getNome()
            });
        }
        txtnome.setText("");
        txtcpf.setText("");
        txttelefone.setText("");
    }
  

