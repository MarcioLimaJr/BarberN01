    private void btnfecharActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfecharActionPerformed
        
        int linha = tabela.getSelectedRow();
        if (linha == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "selecione um atendimento para fechar!");
            return;
            
        } else {
        atendimento atend = new atendimento();
        
            coringaJPA<cliente> cli = new coringaJPA<>(cliente.class);
            coringaJPA<barbeiro> bar = new coringaJPA<>(barbeiro.class);
            coringaJPA<atendente> aten = new coringaJPA<>(atendente.class);
            coringaJPA<servico> ser = new coringaJPA(servico.class);
        
            int id = (int) tabela.getValueAt(linha, 0);
            String nomec = (String)tabela.getValueAt(linha, 1);
            String nomes = (String)tabela.getValueAt(linha, 2);
            String nomea = (String)tabela.getValueAt(linha, 4);
            String nomeb = (String)tabela.getValueAt(linha, 5);
            String data = (String)tabela.getValueAt(linha, 6);
            String hora = (String)tabela.getValueAt(linha, 7);
            String statusSelecionado = (String)tabela.getValueAt(linha, 8);
            boolean status  = false;

            if (statusSelecionado.equals("Fechado")) {
                return;
            }else{
                status = true;
            }
            
            atendente at = aten.buscarPorNome(nomea);
            cliente cl = cli.buscarPorNome(nomec);
            barbeiro ba = bar.buscarPorNome(nomeb);
            servico se = ser.buscarPorNome(nomes);
            
            atend.setIdatendimento(id);
            atend.setAtendente(at);
            atend.setCliente(cl);
            atend.setServico(se);
            atend.setBarbeiro(ba);
            atend.setData(data);
            atend.setHora(hora);
            atend.setStatus(status);
            
            
            a.atualizar(atend);
            
            javax.swing.JOptionPane.showMessageDialog(this,
                    "atendimento fechado!");
        }
       atualizarDados();
        
    }//GEN-LAST:event_btnfecharActionPerformed

    public void iniciartabela() {

        if (table == null) {

            table = new DefaultTableModel(
                    new Object[]{
                        "ID", "Cliente", "Serviço", "Valor Total", "Atendente", "Barbeiro", "Data", "Hora", "Status",}, 0) {

                @Override
                public boolean isCellEditable(int row, int column) {

                    return false; // ID não pode ser alterado

                }
            };

            tabela.setModel(table);
        }

        atualizarDados();
    }

    public void atualizarDados() {

        List<atendimento> lista = a.listar();

        table.setRowCount(0);

        for (atendimento f : lista) {

            table.addRow(new Object[]{
                f.getIdatendimento(),
                f.getCliente().getNome(),
                f.getServico().getNome(),
                f.getServico().getValor(),
                f.getAtendente().getNome(),
                f.getBarbeiro().getNome(),
                f.getData(),
                f.getHora(),
                f.isStatus() ? "Fechado" : "Aberto"
            });
        }
        carregarBox();
    }

    private void carregarBox() {

        coringaJPA<barbeiro> b = new coringaJPA<>(barbeiro.class);

        cbmbarbeiro.removeAllItems();
        cbmbarbeiro.addItem("-");
        
        List<barbeiro> bar = b.listar();
        
        for (barbeiro bb : bar) {
            
            cbmbarbeiro.addItem(bb.getNome());
        }
        
        MaskFormatter mascara = null;

        try {
            mascara = new MaskFormatter("##/##/####");
            mascara.setPlaceholderCharacter('_');
            txtdata.setFormatterFactory(
                    new javax.swing.text.DefaultFormatterFactory(mascara)
            );
        } catch (java.text.ParseException ex) {
            ex.printStackTrace();
        }

    }

