    private void btnbuscaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscaActionPerformed

            String data = txtdata.getText();
            String cliente = txtcliente.getText();
            String barbeiro = cbmbarbeiro.getSelectedItem().toString();

            if (data.equals("") || data.equals("__/__/____")) {
                data = "";
            }

            
           coringaJPA<barbeiro> bar = new coringaJPA<>(barbeiro.class);
            // barbeiro
            barbeiro barbeiroSelecionado = null;
            
            if (barbeiro.equals("-")) {
                barbeiro = "";
            }
            
            barbeiroSelecionado = bar.buscarPorNome(barbeiro);

            // status
            Boolean status = null;

            String statusSelecionado
                    = cbmstatus.getSelectedItem().toString();

            if (statusSelecionado.equals("Fechado")) {
                status = true;
            } else if (statusSelecionado.equals("Aberto")) {
                status = false;
            }

            List<atendimento> lista = a.pesquisarAtendimentos(data,cliente,barbeiroSelecionado,status);

            table.setRowCount(0);

                //enchendo
            for (atendimento f : lista) {

                table.addRow(new Object[]{
                    f.getIdatendimento(),
                    f.getCliente().getNome(),
                    f.getServico().getNome(),
                    f.getServico().getValor(),
                    f.getAtendente().getNome(),
                    f.getBarbeiro().getNome(),
                    f.getData(),
                    f.getHora(),
                    f.isStatus() ? "Fechado" : "Aberto"
                });
            }

    }//GEN-LAST:event_btnbuscaActionPerformed

