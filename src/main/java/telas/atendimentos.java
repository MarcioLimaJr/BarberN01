    private void btnagendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagendarActionPerformed
        
        try {

            String sele = cmbclientes.getSelectedItem().toString();
            String nomec = sele.split("-")[0];
            
            String nomeb = cmbbarbeiros.getSelectedItem().toString();
            
            String sel = cmbservico.getSelectedItem().toString();
            String nomes = sel.split("-")[0];
            
            String hora = cmbhora.getSelectedItem().toString();
            
            String data = txtdata.getText();
            
            coringaJPA<cliente> cl = new coringaJPA<>(cliente.class);
            coringaJPA<barbeiro> bar = new coringaJPA<>(barbeiro.class);
            coringaJPA<atendente> aten = new coringaJPA<>(atendente.class);
            coringaJPA<servico> s = new coringaJPA(servico.class);
            
            cliente cli = cl.buscarPorNome(nomec);
            barbeiro ba = bar.buscarPorNome(nomeb);
            servico ser = s.buscarPorNome(nomes);
            String login =lis.getUsu();
            atendente atend = aten.buscarAtendentePorLogin(login);
            
            if(atend == null){
                JOptionPane.showMessageDialog(null, "seu usuario não é de atendente");
                return;
            }else{
            
            atendimento at = new atendimento();
            at.setAtendente(atend);
            at.setBarbeiro(ba);
            at.setCliente(cli);
            at.setServico(ser);
            at.setHora(hora);
            at.setData(data);
            at.setValorTotal(ser.getValor());
            ate.salvar(at);
            }
          JOptionPane.showMessageDialog(null," Cadastrado com sucesso!");
          } catch (Exception e) {
        JOptionPane.showMessageDialog(this,"Erro ao cadastrar: " + e.getMessage());
        e.printStackTrace();
    }
        
    }//GEN-LAST:event_btnagendarActionPerformed

