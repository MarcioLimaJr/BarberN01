    private void carregarCB() {
    
        coringaJPA<cliente> x = new coringaJPA<>(cliente.class);
        coringaJPA<barbeiro> y = new coringaJPA<>(barbeiro.class);
        coringaJPA<servico> z = new coringaJPA<>(servico.class);

        cmbclientes.removeAllItems();
        cmbbarbeiros.removeAllItems();
        cmbservico.removeAllItems();

        List<cliente> xx = x.listar();
        List<barbeiro> yy = y.listar();
        List<servico> zz = z.listar();

        for (cliente xxx : xx) {

            cmbclientes.addItem(xxx.getNome() + " - " + xxx.getCpf());
        }

        for (barbeiro yyy : yy) {

            cmbbarbeiros.addItem(yyy.getNome());
        }

        for (servico zzz : zz) {

            cmbservico.addItem(zzz.getNome() + " - R$:" + zzz.getValor());
        }

        MaskFormatter mascara = null;
        try {
            mascara = new MaskFormatter("##/##/####");
            mascara.setPlaceholderCharacter('_');
            txtdata.setFormatterFactory(
                    new javax.swing.text.DefaultFormatterFactory(mascara)
            );
        } catch (java.text.ParseException ex) {
            ex.printStackTrace();
        }
    }
    
